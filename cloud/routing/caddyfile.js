import states from '../provisioning/states.js';

const LABEL = /^[a-z0-9](?:[a-z0-9-]{0,61}[a-z0-9])?$/;
const UPSTREAM = /^[a-z0-9.-]+:\d{1,5}$/;
// Mirrors the app's own security headers (server/security/securityHeaders.js). The app sends
// them itself; "?" sets each only when missing, so pages Caddy or the control plane serve carry
// them too. The app's CSP is left to the app, since only it knows what it loads.
const HEADERS = [
  '-Server',
  '?Strict-Transport-Security "max-age=31536000; includeSubDomains"',
  '?X-Content-Type-Options "nosniff"',
  '?X-Frame-Options "DENY"',
  '?Referrer-Policy "no-referrer"',
  '?Cross-Origin-Opener-Policy "same-origin"',
  '?Permissions-Policy "camera=(), microphone=(), geolocation=(), payment=(), usb=(), interest-cohort=()"',
];

// One JSON-RPC relay on a port only workspace networks reach, to `target`: the Ethereum node (or
// the verifier in front of it) on CLOUD_RPC_RELAY_PORT, and in shadow mode the verifier on its
// own port. Workspaces have no other way out.
function relay(port, target, name) {
  const url = new URL(target);
  const rewrite = `${url.pathname}${url.search}`;
  if (/[\s{}"`\\]/.test(rewrite)) throw new Error(`${name} has characters that can’t be written into the Caddy configuration.`);
  const upstream = `${url.protocol}//${url.host}`;
  const lines = [
    `http://:${port} {`,
    '\t# Only workspace networks reach this port: it is not published on the host. Workspaces',
    '\t# have no other way out, so this is their only route to the Ethereum node.',
    '\t@rpc method POST',
    '\thandle @rpc {',
    '\t\trequest_body {',
    '\t\t\tmax_size 1MB',
    '\t\t}',
  ];
  if (rewrite !== '/') lines.push(`\t\trewrite * "${rewrite}"`);
  lines.push(`\t\treverse_proxy ${upstream} {`, '\t\t\theader_up Host {upstream_hostport}');
  if (url.username) lines.push(`\t\t\theader_up Authorization "Basic ${Buffer.from(`${decodeURIComponent(url.username)}:${decodeURIComponent(url.password)}`).toString('base64')}"`);
  lines.push('\t\t}', '\t}', '\thandle {', '\t\trespond 405', '\t}', '}');
  return lines;
}

// The whole Caddy configuration, generated from the control database. Running workspaces are
// proxied to their container; stopped, suspended and deleting ones get a short notice from the
// control plane; anything else under the domain is a 404. TLS is either on demand (one
// certificate per workspace, issued only for names the ask endpoint confirms) or one wildcard
// certificate through a DNS challenge.
export default function caddyfile(config, workspaces, upstream) {
  const { caddy, domain, signupHost } = config;
  for (const value of [caddy.controlUpstream, caddy.askUpstream]) if (!UPSTREAM.test(value)) throw new Error(`Invalid upstream: ${value}`);
  const live = workspaces.filter((w) => LABEL.test(w.name));
  const routed = live.filter((w) => states.routed.includes(w.state));
  const paused = live.filter((w) => states.paused.includes(w.state));
  const delay = caddy.streamCloseDelayMin ? `${caddy.streamCloseDelayMin}m` : null;

  const out = ['# Generated by the Nil control plane from its database. Changes here are overwritten.', '{'];
  if (caddy.acmeEmail) out.push(`\temail ${caddy.acmeEmail}`);
  if (caddy.tls === 'on-demand') out.push('\ton_demand_tls {', `\t\task http://${caddy.askUpstream}/internal/tls`, '\t}');
  out.push('}', '', '(nil_headers) {', '\theader {', ...HEADERS.map((h) => `\t\t${h}`), '\t}', '}', '');
  out.push('(nil_unavailable) {', '\t@nil_page not path /assets/*', '\trewrite @nil_page /unavailable', `\treverse_proxy ${caddy.controlUpstream}`, '}', '');

  out.push(`${signupHost} {`, '\timport nil_headers', '\tencode zstd gzip', '\trequest_body {', '\t\tmax_size 64KB', '\t}', `\treverse_proxy ${caddy.controlUpstream}`, '}', '');

  out.push(`${caddy.tls === 'on-demand' ? 'https://' : `*.${domain}`} {`, '\ttls {');
  out.push(caddy.tls === 'on-demand' ? '\t\ton_demand' : `\t\tdns ${caddy.dnsProvider} {env.${caddy.dnsTokenEnv}}`);
  out.push('\t}', '\timport nil_headers', '\tencode zstd gzip', '');
  for (const w of routed) {
    const target = upstream(w.id);
    if (!UPSTREAM.test(target)) throw new Error(`Invalid upstream for ${w.name}: ${target}`);
    out.push(`\t@w_${w.id} host ${w.name}.${domain}`, `\thandle @w_${w.id} {`);
    // a reload (every sign-up causes one) would otherwise cut every open live connection
    if (delay) out.push(`\t\treverse_proxy ${target} {`, `\t\t\tstream_close_delay ${delay}`, '\t\t}');
    else out.push(`\t\treverse_proxy ${target}`);
    out.push('\t}');
  }
  if (paused.length) out.push(`\t@paused host ${paused.map((w) => `${w.name}.${domain}`).join(' ')}`, '\thandle @paused {', '\t\timport nil_unavailable', '\t}');
  out.push('\thandle {', '\t\trespond "Not found" 404', '\t}', '');
  // a workspace that is starting or has crashed answers 502 for a moment; say so plainly
  out.push('\thandle_errors {', '\t\timport nil_unavailable', '\t}', '}');

  if (config.app.egress === 'rpc-only' && config.app.rpcUrl !== 'off') out.push('', ...relay(caddy.rpcRelayPort, config.app.rpcUrl, 'CLOUD_RPC_URL'));
  if (config.app.egress === 'rpc-only' && config.app.verifierUrl) out.push('', ...relay(caddy.verifierRelayPort, config.app.verifierUrl, 'CLOUD_VERIFIER_URL'));
  return `${out.join('\n')}\n`;
}
