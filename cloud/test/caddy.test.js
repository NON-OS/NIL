const upstream = (id) => `nil-${id}:3000`;
const config = (env = {}) => {
  const { config: c, errors } = loadConfig({ ...baseEnv, CLOUD_ACME_EMAIL: 'ops@nil.test', ...env });
  assert.deepEqual(errors, []);
  return c;
};
const workspaces = [
  { id: 'a1a1a1a1a1a1a1a1', name: 'team', state: 'active' },
  { id: 'b2b2b2b2b2b2b2b2', name: 'newcomer', state: 'provisioning' },
  { id: 'c3c3c3c3c3c3c3c3', name: 'quiet', state: 'suspended' },
  { id: 'd4d4d4d4d4d4d4d4', name: 'closing', state: 'deleting' },
  { id: 'e5e5e5e5e5e5e5e5', name: 'gone', state: 'deleted' },
  { id: 'f6f6f6f6f6f6f6f6', name: 'Bad Name}', state: 'active' },
];

test('on-demand TLS: certificates only for names the ask endpoint confirms, one route per workspace', () => {
  const text = caddyfile(config(), workspaces, upstream);
  assert.match(text, /^# Generated by the Nil control plane/);
  assert.match(text, /\{\n\temail ops@nil\.test\n\ton_demand_tls \{\n\t\task http:\/\/control:8081\/internal\/tls\n\t\}\n\}/);
  assert.match(text, /\nnil\.test \{\n\timport nil_headers\n\tencode zstd gzip\n/);
  assert.match(text, /\nhttps:\/\/ \{\n\ttls \{\n\t\ton_demand\n\t\}/);
  assert.match(text, /@w_a1a1a1a1a1a1a1a1 host team\.nil\.test\n\thandle @w_a1a1a1a1a1a1a1a1 \{\n\t\treverse_proxy nil-a1a1a1a1a1a1a1a1:3000 \{\n\t\t\tstream_close_delay 5m/);
  assert.match(text, /@w_b2b2b2b2b2b2b2b2 host newcomer\.nil\.test/, 'a workspace being created is routed so its certificate can be issued');
  assert.match(text, /@paused host quiet\.nil\.test closing\.nil\.test\n\thandle @paused \{\n\t\timport nil_unavailable/);
  assert.doesNotMatch(text, /gone\.nil\.test/);
  assert.doesNotMatch(text, /Bad Name/, 'a name that isn’t a DNS label never reaches the file');
  assert.match(text, /handle \{\n\t\trespond "Not found" 404/);
  assert.match(text, /handle_errors \{\n\t\timport nil_unavailable/);
  assert.match(text, /\?Strict-Transport-Security "max-age=31536000; includeSubDomains"/);
  assert.match(text, /-Server/);
});

test('wildcard TLS: one certificate through the DNS challenge, token read from Caddy’s environment', () => {
  const text = caddyfile(config({ CLOUD_TLS: 'wildcard', CLOUD_DNS_PROVIDER: 'hetzner' }), workspaces, upstream);
  assert.match(text, /\n\*\.nil\.test \{\n\ttls \{\n\t\tdns hetzner \{env\.DNS_API_TOKEN\}\n\t\}/);
  assert.doesNotMatch(text, /on_demand/);
});

test('with rpc-only egress Caddy relays JSON-RPC to the node; with open egress it doesn’t', () => {
  const relay = caddyfile(config({ CLOUD_RPC_URL: 'https://u:p%40ss@node.example:8545/v3/key?x=1' }), [], upstream);
  assert.match(relay, /http:\/\/:8545 \{/);
  assert.match(relay, /@rpc method POST/);
  assert.match(relay, /rewrite \* "\/v3\/key\?x=1"/);
  assert.match(relay, /reverse_proxy https:\/\/node\.example:8545 \{\n\t\t\theader_up Host \{upstream_hostport\}/);
  assert.match(relay, new RegExp(`header_up Authorization "Basic ${Buffer.from('u:p@ss').toString('base64')}"`));
  assert.match(relay, /respond 405/);
  assert.doesNotMatch(caddyfile(config({ CLOUD_EGRESS: 'open' }), [], upstream), /:8545/);
  assert.doesNotMatch(caddyfile(config({ CLOUD_RPC_URL: 'off' }), [], upstream), /:8545/);
  // braces would be read as a Caddy placeholder; the URL parser leaves them alone in a query
  assert.throws(() => caddyfile(config({ CLOUD_RPC_URL: 'https://node.example/rpc?key={env.SECRET}' }), [], upstream), /can’t be written/);
});

test('route sync writes and reloads only on change, and rolls the file back if Caddy refuses it', async () => {
  const ctx = testContext();
  let refuse = false;
  const reloads = [];
  const routes = createRoutes(ctx, async () => {
    reloads.push(1);
    if (refuse) throw new Error('adapting config: unrecognized directive');
  });
  assert.equal(await routes.sync(), true);
  assert.equal(await routes.sync(), false, 'nothing changed: no reload');
  assert.equal(reloads.length, 1);

  const before = fs.readFileSync(ctx.config.caddy.file, 'utf8');
  createWorkspace(ctx, { name: 'acme', owner: `0x${'d'.repeat(40)}` });
  refuse = true;
  await assert.rejects(routes.sync(), /unrecognized directive/);
  assert.equal(fs.readFileSync(ctx.config.caddy.file, 'utf8'), before, 'the last good file is put back');
  assert.equal(ctx.alerts.at(-1).event, 'routes.reload_failed');

  refuse = false;
  await Promise.all([routes.sync(), routes.sync(), routes.sync()]);
  assert.ok(reloads.length <= 4, 'overlapping syncs are folded together');
  assert.match(fs.readFileSync(ctx.config.caddy.file, 'utf8'), /acme\.nil\.test/);
});

test('the ask endpoint check matches whole labels under the domain only', () => {
  const ctx = testContext();
  createWorkspace(ctx, { name: 'acme', owner: `0x${'d'.repeat(40)}` });
  assert.equal(tlsAllowed(ctx, 'acme.nil.test'), true);
  assert.equal(tlsAllowed(ctx, 'ACME.nil.test'), true);
  assert.equal(tlsAllowed(ctx, 'nil.test'), true);
  for (const host of ['other.nil.test', 'x.acme.nil.test', 'acme.nil.test.example', 'acmenil.test', '', null]) assert.equal(tlsAllowed(ctx, host), false, String(host));
});
